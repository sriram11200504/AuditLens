'use client';

import React from 'react';
import { X, Copy, Download, Check, FileText } from 'lucide-react';
import { Document, Finding } from '@/lib/types';

interface ExportModalProps {
  document: Document;
  findings: Finding[];
  onClose: () => void;
}

function buildMarkdown(document: Document, findings: Finding[]): string {
  const accepted = findings.filter(f => f.userDecision === 'accepted');
  const date = new Date(document.createdAt).toLocaleDateString('en-US', {
    year: 'numeric', month: 'long', day: 'numeric'
  });

  let md = `# NEGOTIATION BRIEF — CONTRACT REDLINE MEMO\n\n`;
  md += `**Document:** ${document.title}  \n`;
  md += `**Audit Date:** ${date}  \n`;
  md += `**Risk Score:** ${document.riskScore}/100  \n`;
  md += `**Model:** ${document.modelUsed}  \n`;
  md += `**Latency:** ${document.latencyMs}ms  \n`;
  md += `\n---\n\n`;
  md += `## ACCEPTED REDLINES (${accepted.length} of ${findings.length} findings)\n\n`;

  if (accepted.length === 0) {
    md += `_No redlines accepted yet. Review the findings and accept proposed redlines to populate this brief._\n`;
  } else {
    accepted.forEach((f, idx) => {
      md += `### ${idx + 1}. ${f.clauseType} — ${f.severity.toUpperCase()} SEVERITY\n\n`;
      md += `**Citation Verified:** ${f.isCitationVerified ? '✅ Verbatim match confirmed' : '⚠️ Unverified'}\n\n`;
      md += `**Original Clause (Verbatim):**\n\n`;
      md += `> ${f.exactQuote}\n\n`;
      md += `**Risk Analysis:**\n\n${f.riskExplanation}\n\n`;
      md += `**Proposed Redline:**\n\n${f.suggestedRedline}\n\n`;
      md += `---\n\n`;
    });
  }

  md += `## OUTSTANDING RISKS (Dismissed or Pending)\n\n`;
  const others = findings.filter(f => f.userDecision !== 'accepted');
  if (others.length === 0) {
    md += `_All findings triaged._\n`;
  } else {
    others.forEach(f => {
      md += `- **${f.clauseType}** (${f.severity}) — ${f.userDecision} — ${f.riskExplanation}\n`;
    });
  }

  md += `\n---\n_Generated by AuditLens · AI Contract & SLA Risk Triage Platform_\n`;
  return md;
}

export default function ExportModal({ document, findings, onClose }: ExportModalProps) {
  const [copied, setCopied] = React.useState(false);
  const markdown = buildMarkdown(document, findings);

  const handleCopy = async () => {
    await navigator.clipboard.writeText(markdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdown], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = window.document.createElement('a');
    a.href = url;
    a.download = `auditlens-brief-${document.id.slice(0, 8)}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 bg-black/40 backdrop-blur-sm z-50 flex items-center justify-center p-4">
      <div className="bg-white rounded-2xl border border-[#E5E7EB] shadow-2xl w-full max-w-2xl max-h-[85vh] flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-[#E5E7EB]">
          <div className="flex items-center gap-2">
            <FileText size={16} className="text-[#0F172A]" />
            <span className="font-semibold text-[#0F172A]">Export Negotiation Brief</span>
          </div>
          <button onClick={onClose} className="p-1 hover:bg-[#F3F4F6] rounded-lg transition-colors">
            <X size={16} />
          </button>
        </div>

        {/* Meta */}
        <div className="px-6 py-3 bg-[#F9FAFB] border-b border-[#E5E7EB]">
          <div className="flex flex-wrap gap-4 text-xs text-[#6B7280]">
            <span><strong className="text-[#374151]">Doc:</strong> {document.title}</span>
            <span><strong className="text-[#374151]">Accepted:</strong> {findings.filter(f => f.userDecision === 'accepted').length} redlines</span>
            <span><strong className="text-[#374151]">Risk Score:</strong> {document.riskScore}/100</span>
          </div>
        </div>

        {/* Preview */}
        <div className="flex-1 overflow-y-auto px-6 py-4">
          <pre className="text-xs text-[#374151] font-mono whitespace-pre-wrap leading-relaxed bg-[#F9FAFB] border border-[#E5E7EB] rounded-lg p-4">
            {markdown}
          </pre>
        </div>

        {/* Footer buttons */}
        <div className="px-6 py-4 border-t border-[#E5E7EB] flex justify-end gap-2">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-4 py-2 text-sm font-medium text-[#374151] border border-[#E5E7EB] bg-white rounded-lg hover:bg-[#F9FAFB] transition-colors"
          >
            {copied ? <Check size={14} className="text-emerald-600" /> : <Copy size={14} />}
            {copied ? 'Copied!' : 'Copy to Clipboard'}
          </button>
          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-4 py-2 text-sm font-medium text-white bg-[#0F172A] rounded-lg hover:bg-[#1E293B] transition-colors"
          >
            <Download size={14} />
            Download .md
          </button>
        </div>
      </div>
    </div>
  );
}

